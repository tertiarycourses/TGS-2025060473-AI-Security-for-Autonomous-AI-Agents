                       ("headers", headers), ("rows", rows), ("left", left),
                       ("right", right), ("steps", steps), ("note", note),
                       ("anchor", anchor), ("image", image), ("lhead", lhead),
                       ("rhead", rhead), ("cols", cols), ("widths", widths),
